    testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
  }

  signingConfigs {
    create("release") {
      val keystore = file(System.getenv("KEYSTORE_PATH") ?: "${rootDir}/my-upload-key.jks")
      if (keystore.exists()) {
        storeFile = keystore
        storePassword = System.getenv("STORE_PASSWORD")
        keyAlias = System.getenv("KEY_ALIAS") ?: "upload"
        keyPassword = System.getenv("KEY_PASSWORD")
      }
    }
    create("debugConfig") {
      val keystore = file("${rootDir}/debug.keystore")
      if (keystore.exists()) {
        storeFile = keystore
        storePassword = "android"
        keyAlias = "androiddebugkey"
        keyPassword = "android"
      }
    }
  }

  buildTypes {
    release {
      isCrunchPngs = false
      isMinifyEnabled = false
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      // Only sign when a keystore is actually present, so a release build on a machine
      // without one produces an unsigned APK instead of failing at the last step.
      signingConfig = signingConfigs.getByName("release").takeIf { it.storeFile?.exists() == true }
    }
    debug {
      signingConfig = signingConfigs.getByName("debugConfig").takeIf { it.storeFile?.exists() == true }
        ?: signingConfigs.getByName("debug")
    }
  }

